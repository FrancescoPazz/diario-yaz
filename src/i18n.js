/** Lingua da usare: quella scelta nelle Impostazioni, altrimenti italiano se il telefono è in italiano, inglese in tutti gli altri casi. */
export const pickLang = (setting, nav) => setting === 'it' || setting === 'en' ? setting : /^it\b/i.test(nav || '') ? 'it' : 'en';

/** Testi e formati di data per una lingua. Le date sono numeri di giorno (vedi logic.js). */
export function strings(lang) {
  const loc = lang === 'it' ? 'it-IT' : 'en-GB';
  const date = (n, o) => new Date(n * DAY).toLocaleDateString(loc, { ...o, timeZone: 'UTC' });
  const relFmt = new Intl.RelativeTimeFormat(lang, { numeric: 'auto' });
  const L = {
    ...TEXT[lang], lang,
    fmt: n => date(n, { weekday: 'short', day: 'numeric', month: 'short' }),
    fmtLong: n => date(n, { weekday: 'long', day: 'numeric', month: 'long' }),
    fmtFull: n => date(n, { day: 'numeric', month: 'long', year: 'numeric' }),
    monthTitle: n => date(n, { month: 'long', year: 'numeric' }),
    rel: (n, t) => relFmt.format(n - t, 'day'),
    weekdays: Array.from({ length: 7 }, (_, i) => date(19723 + i, { weekday: 'narrow' })),   // 19723 = lunedì 1 gennaio 2024
  };
  L.msg = TEXT[lang].msg(L);
  return L;
}
